// Lays out one directory per platform under dist/platforms/<name>/: the adapter where the platform expects its entry, the runtime, the
// module and the platform's configuration — what `wrangler deploy`, `vercel deploy`, `netlify deploy` or `deno deploy` takes as it is.
//   node build/package.mjs [platform …]          platforms: node bun deno cloudflare vercel netlify   (default: all)
import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const host = `${root}host/`;
const out = `${root}dist/platforms/`;
const wasm = process.env.GHOST_WASM ?? `${root}fixtures/GhostTodo.wasm`;        // the module to package: the fixture, or one just built

execFileSync(process.execPath, [`${root}build/assets.mjs`], { stdio: "inherit" });
const bytes = await readFile(wasm).catch(() => { throw new Error(`${wasm} is missing: GHOST_WASM names the module to package (default fixtures/GhostTodo.wasm)`); });

const esm = JSON.stringify({ type: "module", private: true });
// platform -> files: [from (below host/adapters/<platform>/), to (below dist/platforms/<platform>/)]
const layouts = {
  node: { files: [["index.mjs", "index.mjs"]], extra: { "package.json": esm } },
  bun: { files: [["index.mjs", "index.mjs"]], extra: { "package.json": esm } },
  deno: { files: [["main.mjs", "main.mjs"], ["deno.json", "deno.json"]] },
  cloudflare: { files: [["worker.js", "worker.js"], ["wrangler.toml", "wrangler.toml"]], extra: { "package.json": esm } },
  vercel: {
    files: [["api-edge.js", "api/edge.js"], ["api-node.mjs", "api/node.mjs"], ["vercel.json", "vercel.json"]],
    extra: { "package.json": esm },
  },
  netlify: {
    files: [["edge-ghost.mjs", "netlify/edge-functions/ghost.mjs"], ["function-ghost.mjs", "netlify/functions/ghost.mjs"], ["netlify.toml", "netlify.toml"]],
    extra: {
      "package.json": esm,
      // `netlify deploy` wants a publish directory; the edge function answers every path before it is looked at
      "public/index.html": "<!doctype html><title>ghost-todo</title><p>Served by the edge function (netlify/edge-functions/ghost.mjs).</p>\n",
      // an edge function cannot read files: the module's bytes travel as a module
      "wasm-bytes.js": `// generated by build/package.mjs\nconst b64 = "${bytes.toString("base64")}";\nexport default Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));\n`,
    },
  },
};

const wanted = process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(layouts);
for (const name of wanted) {
  const layout = layouts[name];
  if (!layout) throw new Error(`unknown platform ${name}`);
  const dir = `${out}${name}/`;
  await rm(dir, { recursive: true, force: true });
  await mkdir(`${dir}runtime`, { recursive: true });
  for (const f of ["server.js", "stores.js", "assets.js", "shared.js"]) await cp(`${host}runtime/${f}`, `${dir}runtime/${f}`);
  await writeFile(`${dir}GhostTodo.wasm`, bytes);
  for (const [from, to] of layout.files) {
    await mkdir(new URL(`file://${dir}${to}/..`), { recursive: true });
    await cp(`${host}adapters/${name}/${from}`, `${dir}${to}`);
  }
  for (const [file, content] of Object.entries(layout.extra ?? {})) {
    await mkdir(dirname(`${dir}${file}`), { recursive: true });
    await writeFile(`${dir}${file}`, content);
  }
  console.log(`packaged ${name}: dist/platforms/${name}/`);
}
