// Generates host/runtime/assets.js: the files a host serves before it asks the module — the client page with the GGBP client
// inlined (one page, no further requests), and the canvas client (fixtures/canvas: its page, its module and the runtime it loads) below /canvas/.
// A platform bundle is made from this file, so the pages need nothing but JavaScript to ship.
//   node build/assets.mjs
import { readFile, readdir, stat, writeFile } from "node:fs/promises";
import { extname } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const source = await readFile(`${root}host/client/ggbp.js`, "utf8");
const ggbp = source.replace(/^export /gm, "");
const index = (await readFile(`${root}host/client/index.html`, "utf8")).replace("/*GGBP*/", () => ggbp);
const files = {
  "/": { type: "text/html; charset=utf-8", body: index },
  "/ggbp.js": { type: "text/javascript; charset=utf-8", body: source },
};

// the canvas client: the page and what it loads, as the backend's build makes them (dist/canvas), checked in as a fixture with its provenance
const types = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".wasm": "application/wasm" };
const canvasDir = `${root}fixtures/canvas`;
const canvas = [];
for (const rel of await readdir(canvasDir, { recursive: true }).catch(() => [])) if ((await stat(`${canvasDir}/${rel}`)).isFile()) canvas.push(rel);
for (const file of canvas.sort()) {
  const bytes = await readFile(`${canvasDir}/${file}`);
  const type = types[extname(file)] ?? "application/octet-stream";
  files[file === "index.html" ? "/canvas/" : `/canvas/${file}`] = extname(file) === ".wasm" ? { type, base64: bytes.toString("base64") } : { type, body: bytes.toString("utf8") };
}
if (canvas.length) files["/canvas"] = { redirect: "canvas/" };
await writeFile(`${root}host/runtime/assets.js`, `// generated by build/assets.mjs from host/client — do not edit\nexport const assets = ${JSON.stringify(files, null, 2)};\n`);
console.log(`assets: ${Object.keys(files).length} files (${canvas.length} of the canvas client)`);
