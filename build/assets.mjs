// Generates host/runtime/assets.js: the files a host serves before it asks the module — the client page with the GGBP client
// inlined (one page, no further requests).  A platform bundle is made from this file, so the page needs nothing but JavaScript to ship.
//   node build/assets.mjs
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const source = await readFile(`${root}host/client/ggbp.js`, "utf8");
const ggbp = source.replace(/^export /gm, "");
const index = (await readFile(`${root}host/client/index.html`, "utf8")).replace("/*GGBP*/", () => ggbp);
const files = {
  "/": { type: "text/html; charset=utf-8", body: index },
  "/ggbp.js": { type: "text/javascript; charset=utf-8", body: source },
};
await writeFile(`${root}host/runtime/assets.js`, `// generated by build/assets.mjs from host/client — do not edit\nexport const assets = ${JSON.stringify(files, null, 2)};\n`);
console.log(`assets: ${Object.keys(files).join(", ")} (${index.length} bytes of page)`);
